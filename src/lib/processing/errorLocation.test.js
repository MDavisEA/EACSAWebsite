import { locateRuntimeError, parseStack, hintsFromMessage, explainError } from "./errorLocation.js";

let failed = 0;
const eq = (name, got, want) => {
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    failed++;
    console.log("FAIL ", name, "\n  got: ", JSON.stringify(got), "\n  want:", JSON.stringify(want));
  } else console.log("ok   ", name);
};

// A student's sketch (line numbers matter - see the comments on the right) ...
