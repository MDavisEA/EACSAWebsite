// the same misspelling in two places: answer with one, mention the other
const SRC_TWICE = SRC_TYPO.replace("fill(10);", "fill(scor);");
const GEN_TWICE = GEN_TYPO.replace("$p.fill(10);", "$p.fill(scor);");
