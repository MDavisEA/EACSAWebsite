// A V8 frame for code made with `new Function`: the body's line N is reported as N + 2.
const frame = (genLine, fn) => `    at ${fn} (eval at start (about:srcdoc:1:2), <anonymous>:${genLine + 2}:5)`;
const stackAt = (genLine, fn) => `ReferenceError: x\n    at lib.thrower (about:srcdoc:12:3)\n${frame(genLine, fn)}\n    at ir.redraw (about:srcdoc:893:36)`;
const genLineOf = (gen, needle) => gen.split("\n").findIndex((l) => l.includes(needle)) + 1;
const locate = (src, gen, needle, fn, message) =>
  locateRuntimeError({ preprocessed: src, generated: gen, stack: stackAt(genLineOf(gen, needle), fn), message });

// ---- reading a stack trace
eq("stack: a Chrome frame", parseStack(stackAt(10, "draw"), 57), { genLine: 10, fn: "draw" });
eq("stack: skips Processing.js's own frames", parseStack("Error\n    at lib (about:srcdoc:893:36)\n" + frame(7, "setup"), 57), { genLine: 7, fn: "setup" });
eq("stack: a line past the end of the sketch is the library, not the student", parseStack("Error\n    at lib (eval at x, <anonymous>:893:36)", 57), null);
eq("stack: a Firefox frame", parseStack("draw@about:srcdoc line 1 > Function:12:3", 57), { genLine: 10, fn: "draw" });
eq("stack: empty", parseStack("", 57), null);

// ---- what the message points at
eq("hint: not defined", hintsFromMessage("Uncaught ReferenceError: ballX is not defined"), ["ballX"]);
eq("hint: not a function", hintsFromMessage("TypeError: drawBall is not a function"), ["drawBall"]);
